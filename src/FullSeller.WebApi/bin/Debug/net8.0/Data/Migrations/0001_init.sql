-- FULL SELLER — начальная схема БД (MS SQL Server)
-- Применяется по порядку номеров файлов (0001_, 0002_, ...) простым раннером при старте приложения.

CREATE TABLE Users (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    Phone NVARCHAR(20) NOT NULL,
    FullName NVARCHAR(200) NULL,
    Role INT NOT NULL DEFAULT 0,
    IsLegalEntity BIT NOT NULL DEFAULT 0,
    LegalName NVARCHAR(300) NULL,
    TaxId NVARCHAR(50) NULL,
    LoyaltyPoints INT NOT NULL DEFAULT 0,
    Language NVARCHAR(10) NOT NULL DEFAULT 'ru',
    PreferredCurrency NVARCHAR(10) NOT NULL DEFAULT 'RUB',
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    CONSTRAINT UQ_Users_Phone UNIQUE (Phone)
);

CREATE TABLE Addresses (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    Country INT NOT NULL,
    City NVARCHAR(100) NOT NULL,
    Line NVARCHAR(300) NOT NULL,
    IsDefault BIT NOT NULL DEFAULT 0
);
CREATE INDEX IX_Addresses_UserId ON Addresses(UserId);

CREATE TABLE OtpCodes (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    Phone NVARCHAR(20) NOT NULL,
    CodeHash NVARCHAR(200) NOT NULL,
    ExpiresAt DATETIME2 NOT NULL,
    Attempts INT NOT NULL DEFAULT 0,
    IsUsed BIT NOT NULL DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
CREATE INDEX IX_OtpCodes_Phone_ExpiresAt ON OtpCodes(Phone, ExpiresAt);

CREATE TABLE RefreshTokens (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    TokenHash NVARCHAR(200) NOT NULL,
    ExpiresAt DATETIME2 NOT NULL,
    RevokedAt DATETIME2 NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
CREATE INDEX IX_RefreshTokens_UserId_ExpiresAt ON RefreshTokens(UserId, ExpiresAt);

CREATE TABLE Categories (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    Name NVARCHAR(150) NOT NULL,
    Slug NVARCHAR(150) NOT NULL,
    ParentCategoryId UNIQUEIDENTIFIER NULL REFERENCES Categories(Id)
);

CREATE TABLE Brands (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    Name NVARCHAR(150) NOT NULL,
    LogoUrl NVARCHAR(500) NULL
);

CREATE TABLE Products (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    Name NVARCHAR(300) NOT NULL,
    CategoryId UNIQUEIDENTIFIER NOT NULL REFERENCES Categories(Id),
    BrandId UNIQUEIDENTIFIER NULL REFERENCES Brands(Id),
    Description NVARCHAR(MAX) NULL,
    Composition NVARCHAR(500) NULL,
    BaseSku NVARCHAR(50) NOT NULL,
    WeightGrams INT NOT NULL DEFAULT 0,
    ImageUrlsJson NVARCHAR(MAX) NOT NULL DEFAULT '[]',
    Rating DECIMAL(3,2) NOT NULL DEFAULT 0,
    ReviewsCount INT NOT NULL DEFAULT 0,
    IsActive BIT NOT NULL DEFAULT 1,
    MinPrice DECIMAL(10,2) NOT NULL DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
CREATE INDEX IX_Products_CategoryId ON Products(CategoryId);
CREATE INDEX IX_Products_BrandId ON Products(BrandId);

CREATE TABLE ProductVariants (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    ProductId UNIQUEIDENTIFIER NOT NULL REFERENCES Products(Id),
    Size NVARCHAR(20) NULL,
    Color NVARCHAR(50) NULL,
    Sku NVARCHAR(50) NOT NULL,
    StockQuantity INT NOT NULL DEFAULT 0,
    CONSTRAINT UQ_ProductVariants_Sku UNIQUE (Sku)
);
CREATE INDEX IX_ProductVariants_ProductId ON ProductVariants(ProductId);

CREATE TABLE PriceTiers (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    ProductId UNIQUEIDENTIFIER NOT NULL REFERENCES Products(Id),
    MinQuantity INT NOT NULL,
    PricePerUnit DECIMAL(10,2) NOT NULL
);
CREATE INDEX IX_PriceTiers_ProductId_MinQuantity ON PriceTiers(ProductId, MinQuantity);

CREATE TABLE Carts (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    PromoCodeId UNIQUEIDENTIFIER NULL,
    CONSTRAINT UQ_Carts_UserId UNIQUE (UserId)
);

CREATE TABLE CartItems (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    CartId UNIQUEIDENTIFIER NOT NULL REFERENCES Carts(Id),
    ProductVariantId UNIQUEIDENTIFIER NOT NULL REFERENCES ProductVariants(Id),
    Quantity INT NOT NULL
);
CREATE INDEX IX_CartItems_CartId ON CartItems(CartId);

CREATE TABLE Orders (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    OrderNumber NVARCHAR(30) NOT NULL,
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    Status INT NOT NULL DEFAULT 0,
    DeliveryCountry INT NOT NULL,
    AddressId UNIQUEIDENTIFIER NOT NULL REFERENCES Addresses(Id),
    PaymentMethod INT NOT NULL,
    TotalAmount DECIMAL(12,2) NOT NULL,
    DeliveryCost DECIMAL(10,2) NOT NULL DEFAULT 0,
    CargoTrackingNumber NVARCHAR(100) NULL,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    CONSTRAINT UQ_Orders_OrderNumber UNIQUE (OrderNumber)
);
CREATE INDEX IX_Orders_UserId ON Orders(UserId);
CREATE INDEX IX_Orders_Status ON Orders(Status);

CREATE TABLE OrderItems (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    OrderId UNIQUEIDENTIFIER NOT NULL REFERENCES Orders(Id),
    ProductVariantId UNIQUEIDENTIFIER NOT NULL REFERENCES ProductVariants(Id),
    Quantity INT NOT NULL,
    UnitPriceAtOrderTime DECIMAL(10,2) NOT NULL
);
CREATE INDEX IX_OrderItems_OrderId ON OrderItems(OrderId);

CREATE TABLE OrderStatusEvents (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    OrderId UNIQUEIDENTIFIER NOT NULL REFERENCES Orders(Id),
    Status INT NOT NULL,
    Comment NVARCHAR(500) NULL,
    ChangedByUserId UNIQUEIDENTIFIER NULL,
    ChangedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
CREATE INDEX IX_OrderStatusEvents_OrderId_ChangedAt ON OrderStatusEvents(OrderId, ChangedAt);

CREATE TABLE Reviews (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    ProductId UNIQUEIDENTIFIER NOT NULL REFERENCES Products(Id),
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    OrderId UNIQUEIDENTIFIER NOT NULL REFERENCES Orders(Id),
    Rating INT NOT NULL,
    Text NVARCHAR(MAX) NULL,
    PhotoUrlsJson NVARCHAR(MAX) NOT NULL DEFAULT '[]',
    Status INT NOT NULL DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
CREATE INDEX IX_Reviews_ProductId ON Reviews(ProductId);
CREATE INDEX IX_Reviews_Status ON Reviews(Status);

CREATE TABLE Favorites (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    ProductId UNIQUEIDENTIFIER NOT NULL REFERENCES Products(Id),
    CONSTRAINT UQ_Favorites_User_Product UNIQUE (UserId, ProductId)
);

CREATE TABLE ChatMessages (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    SenderType INT NOT NULL,
    Text NVARCHAR(MAX) NOT NULL,
    AttachmentUrl NVARCHAR(500) NULL,
    SentAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    IsRead BIT NOT NULL DEFAULT 0
);
CREATE INDEX IX_ChatMessages_UserId_SentAt ON ChatMessages(UserId, SentAt);

CREATE TABLE Notifications (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    Type INT NOT NULL,
    Title NVARCHAR(200) NOT NULL,
    Body NVARCHAR(1000) NOT NULL,
    IsRead BIT NOT NULL DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
CREATE INDEX IX_Notifications_UserId_IsRead ON Notifications(UserId, IsRead);

CREATE TABLE PromoCodes (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    Code NVARCHAR(50) NOT NULL,
    DiscountType INT NOT NULL,
    DiscountValue DECIMAL(10,2) NOT NULL,
    ExpiresAt DATETIME2 NULL,
    UsageLimit INT NULL,
    TimesUsed INT NOT NULL DEFAULT 0,
    CONSTRAINT UQ_PromoCodes_Code UNIQUE (Code)
);

CREATE TABLE CargoRates (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
    Country INT NOT NULL,
    PricePerKg DECIMAL(10,2) NOT NULL,
    Currency NVARCHAR(10) NOT NULL DEFAULT 'RUB',
    CONSTRAINT UQ_CargoRates_Country UNIQUE (Country)
);

